/**
  ******************************************************************************
  * @file    mpu6050.h
  * @brief   MPU6050 六轴传感器驱动（本项目只用加速度计）
  *
  * 这是一个可复用的小驱动：只做两件事——初始化、读三轴加速度原始值。
  * 走 I2C，和 OLED 共用同一条总线（见 main.c 的接线说明），所以这里不自己
  * 初始化 I2C 引脚，直接用 my_lib/i2c.c 里的收发函数即可。
  ******************************************************************************
  */
#ifndef _MPU6050_H_
#define _MPU6050_H_

#include "stm32f10x.h"

/* I2C 从机地址：AD0 接 GND 时 7 位地址是 0x68，左移一位成 8 位写地址 0xD0。
 * （my_lib/i2c.c 的收发函数要的就是这个 8 位地址） */
#define MPU6050_ADDR        0xD0

/* 加速度量程 ±2g 时：1g 对应 16384 个原始值（LSB） */
#define MPU6050_LSB_PER_G   16384.0f

/* 三轴加速度原始值（有符号，正负对应两个相反方向） */
typedef struct
{
    int16_t ax;
    int16_t ay;
    int16_t az;
} MPU6050_Accel;

// @简介：初始化 MPU6050（唤醒 + 设采样率 + 开低通滤波 + 设量程）
// @参数：I2Cx - 使用的 I2C 接口，填 I2C1
// @返回值：0 - 成功；-1 - 没找到器件（I2C 不通或地址不对）
int MPU6050_Init(I2C_TypeDef *I2Cx);

// @简介：读取三轴加速度原始值
// @参数：I2Cx  - 使用的 I2C 接口
// @参数：accel - 输出参数，读到的 X/Y/Z 原始值
// @返回值：0 - 成功；-1 - 读取失败
int MPU6050_ReadAccel(I2C_TypeDef *I2Cx, MPU6050_Accel *accel);

// @简介：读取 WHO_AM_I(ID) 寄存器，用来确认器件在不在、是不是 MPU6050
// @参数：I2Cx - 使用的 I2C 接口
// @参数：pId  - 输出参数，读到的 ID（正常是 0x68）
// @返回值：0 - 成功；-1 - 读取失败
int MPU6050_ReadID(I2C_TypeDef *I2Cx, uint8_t *pId);

#endif
